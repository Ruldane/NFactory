"""AI-generated marking (AI Act art. 50(2), ADR-0014): every delivery carries a
machine-readable manifest saying it was generated by AI, by which engines, and the
hash of each delivered file."""

import hashlib
import io
import json
import zipfile
from pathlib import Path

from nfactory_core.routing import ROLES
from nfactory_core.workspace import Workspace
from nfactory_worker.agents import Engines, demo_llm
from nfactory_worker.artifacts import (
    AI_NOTICE,
    DIGITAL_SOURCE_TYPE,
    PROVENANCE_FILE,
    provenance_manifest,
    zip_workspace,
)


def workspace(tmp_path: Path) -> Workspace:
    ws = Workspace.create(tmp_path, "run_prov")
    ws.write_files(
        {
            "README.md": "# Rapport\n",
            "build_report.py": "print('ok')\n",
            ".nfactory/junit.xml": "<testsuite/>",
        }
    )
    return ws


def test_the_manifest_says_ai_generated_in_a_standard_vocabulary(tmp_path: Path) -> None:
    manifest = provenance_manifest(
        workspace(tmp_path),
        run_id="run_prov",
        project_type="excel",
        recipe_kind="excel-automation",
        engines=Engines.single(demo_llm()),
    )

    assert manifest["ai_generated"] is True
    assert manifest["digital_source_type"] == DIGITAL_SOURCE_TYPE
    assert DIGITAL_SOURCE_TYPE.endswith("/trainedAlgorithmicMedia")
    assert manifest["generator"] == "NFactory"
    assert manifest["notice"] == AI_NOTICE and "généré par IA" in AI_NOTICE
    assert (manifest["run_id"], manifest["project_type"]) == ("run_prov", "excel")
    assert manifest["recipe"] == "excel-automation"


def test_the_manifest_names_the_engine_of_every_role(tmp_path: Path) -> None:
    manifest = provenance_manifest(
        workspace(tmp_path),
        run_id="run_prov",
        project_type="excel",
        recipe_kind="excel-automation",
        engines=Engines.single(demo_llm()),
    )

    roles = [engine["role"] for engine in manifest["engines"]]
    assert roles == sorted(ROLES)
    first = manifest["engines"][0]
    assert set(first) == {"role", "provider", "model", "demo"}
    assert first["demo"] is True


def test_the_manifest_hashes_each_delivered_file_but_not_run_internals(tmp_path: Path) -> None:
    ws = workspace(tmp_path)

    manifest = provenance_manifest(
        ws,
        run_id="run_prov",
        project_type="excel",
        recipe_kind="excel-automation",
        engines=Engines.single(demo_llm()),
    )

    expected = hashlib.sha256(b"print('ok')\n").hexdigest()
    assert manifest["files"] == [
        {"path": "README.md", "sha256": hashlib.sha256(b"# Rapport\n").hexdigest()},
        {"path": "build_report.py", "sha256": expected},
    ]


def test_the_zip_ships_the_manifest_and_still_drops_run_internals(tmp_path: Path) -> None:
    ws = workspace(tmp_path)
    manifest = provenance_manifest(
        ws,
        run_id="run_prov",
        project_type="excel",
        recipe_kind="excel-automation",
        engines=Engines.single(demo_llm()),
    )
    ws.write_files({PROVENANCE_FILE: json.dumps(manifest)})

    names = zipfile.ZipFile(io.BytesIO(zip_workspace(ws))).namelist()

    assert PROVENANCE_FILE in names
    assert ".nfactory/junit.xml" not in names
