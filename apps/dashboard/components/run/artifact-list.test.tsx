import { render, screen } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import { ArtifactList } from "@/components/run/artifact-list";
import type { Artifact } from "@/lib/api/types";

const ZIP: Artifact = {
  id: "art_1",
  filename: "rapport.zip",
  mime: "application/zip",
  size: 2048,
  checksum: "sha256:0123456789abcdef0123456789abcdef",
  created_at: "2026-11-03T10:00:00Z",
  download_url: "/api/v1/artifacts/art_1/download",
};

describe("ArtifactList", () => {
  it("marks the deliverables as generated by AI and names the manifest", () => {
    render(<ArtifactList artifacts={[ZIP]} />);

    const note = screen.getByRole("note");
    expect(note).toHaveTextContent("Livrables générés par IA");
    expect(note).toHaveTextContent(".nfactory/provenance.json");
  });

  it("says nothing about AI before there is a deliverable", () => {
    render(<ArtifactList artifacts={[]} />);

    expect(screen.queryByRole("note")).not.toBeInTheDocument();
  });
});
